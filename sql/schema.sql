CREATE TABLE IF NOT EXISTS rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL,
    price_per_night NUMERIC(10, 2) NOT NULL
        CHECK (price_per_night >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id BIGINT NOT NULL
        REFERENCES rooms(id) ON DELETE CASCADE,
    date_start DATE NOT NULL,
    date_end DATE NOT NULL,
    CONSTRAINT valid_booking_dates
        CHECK (date_end > date_start)
);

CREATE INDEX IF NOT EXISTS idx_rooms_price
    ON rooms (price_per_night);

CREATE INDEX IF NOT EXISTS idx_rooms_created
    ON rooms (created_at);

CREATE INDEX IF NOT EXISTS idx_bookings_room_start
    ON bookings (room_id, date_start);